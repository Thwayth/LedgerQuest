// Small deterministic PRNG (mulberry32) seeded from the date string.
function seededRandom(seedStr) {
  let h = 2166136261;
  for (const ch of seedStr) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  let a = h >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Each user gets their own random set for the day (seeded by day + user id),
// so questions differ between players but stay stable if the same user
// reopens the app on the same day.
export function questionsForDay(day, count, userKey = "") {
  const rand = seededRandom(`ledger-quest:${day}:${userKey}`);
  const pool = [...QUESTION_POOL];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  // Also shuffle the answer options, so the right answer isn't always "A"
  // and doesn't sit in the same place every time a question comes back.
  return pool.slice(0, Math.min(count, pool.length)).map(q => {
    const order = q.options.map((_, i) => i);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [order[i], order[j]] = [order[j], order[i]];
    }
    return {
      ...q,
      options: order.map(i => q.options[i]),
      correct: order.indexOf(q.correct)
    };
  });
}
